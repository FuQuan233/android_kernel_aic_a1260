#ifndef __MFD_MT6350_REGISTERS_H__
#define __MFD_MT6350_REGISTERS_H__

/* MT6580 BSP MT6350 register map; addresses are 16-bit byte offsets. */
#define MT6350_CID		0x0100
#define MT6350_TOP_CKPDN0		0x0102
#define MT6350_TOP_CKPDN1		0x0108
#define MT6350_TOP_CKPDN2		0x010e
#define MT6350_TOP_RST_MISC	0x011a
#define MT6350_CHRSTATUS		0x0142
#define MT6350_INT_CON0		0x0160
#define MT6350_INT_CON1		0x0166
#define MT6350_INT_MISC_CON	0x016c
#define MT6350_INT_STATUS0	0x0172
#define MT6350_INT_STATUS1	0x0174
#define MT6350_AUXADC_ADC0	0x0714
#define MT6350_AUXADC_ADC3	0x071a
#define MT6350_AUXADC_ADC9	0x0726
#define MT6350_AUXADC_CON11	0x0758
#define MT6350_AUXADC_CON22	0x076e

#define MT6350_IRQ_PWRKEY		5
#define MT6350_IRQ_CHRDET		10
#define MT6350_IRQ_FCHRKEY	17
#define MT6350_IRQ_RTC		20

#endif
