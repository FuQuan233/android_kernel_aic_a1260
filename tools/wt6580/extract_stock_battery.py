"""Recover the battery curves from the verified normal A1260 kernel backup.

Input is the kallsyms-reconstructed ELF recorded in wt6580-we-n.rst.
Addresses come from fgauge_get_profile{,_r_table} literal pools. Do not
apply these addresses to a different firmware image.
"""
import argparse
import hashlib
import struct
from pathlib import Path

SOURCE_SHA256 = '71fd8423c76ad1dad2af923988e8e5362ac9d314b6f436370b548c3200d784b6'
OCV = (0xc0e73dbc, 0xc0e740ec, 0xc0e7441c, 0xc0e7474c)
RESISTANCE = (0xc0e74a7c, 0xc0e74dac, 0xc0e750dc, 0xc0e7540c)


def extract(data):
    if hashlib.sha256(data).hexdigest() != SOURCE_SHA256:
        raise ValueError('Input is not the verified A1260 kernel ELF')
    phoff = struct.unpack_from('<I', data, 28)[0]
    phentsize, phnum = struct.unpack_from('<HH', data, 42)
    segments = [struct.unpack_from('<8I', data, phoff + i * phentsize)
                for i in range(phnum)]

    def pairs(address):
        for typ, off, va, _, size, _, _, _ in segments:
            if typ == 1 and va <= address and address + 102 * 8 <= va + size:
                return [struct.unpack_from('<ii', data, off + address - va + i * 8)
                        for i in range(102)]
        raise ValueError(f'Table at {address:#x} is not file-backed')

    lines = [
        '/* SPDX-License-Identifier: GPL-2.0-only */',
        '/* Generated by tools/wt6580/extract_stock_battery.py.',
        f' * Verified kernel ELF SHA256: {SOURCE_SHA256}',
        ' * Factory effective Qmax is independent of label design capacity.',
        ' * These original curves are not a new calibration of the aged cell.',
        ' */',
        '#ifndef _MT6350_BATTERY_PROFILE_H',
        '#define _MT6350_BATTERY_PROFILE_H', '',
        '#define MT6350_PROFILE_SIZE 102', '',
        'struct mt6350_profile_point {',
        '\tint dod;', '\tint mv;', '\tint mohms;', '};', '',
        'static const int mt6350_profile_temps[] = { -10, 0, 25, 50 };',
        'static const int mt6350_factory_qmax[] = { 1600, 1798, 1838, 1815 };', '',
        'static const struct mt6350_profile_point',
        'mt6350_factory_profiles[4][MT6350_PROFILE_SIZE] = {',
    ]
    for temp, a, b in zip((-10, 0, 25, 50), OCV, RESISTANCE):
        lines.append(f'\t{{ /* {temp} C: OCV {a:#x}, resistance {b:#x}. */')
        for (dod, mv), (r, r_mv) in zip(pairs(a), pairs(b)):
            if not 0 <= dod <= 101 or not 2500 <= mv <= 4500 or not 0 < r < 10000:
                raise ValueError('Invalid factory profile point')
            if mv != r_mv:
                raise ValueError('OCV and resistance voltage grids differ')
            lines.append(f'\t\t{{ {dod}, {mv}, {r} }},')
        lines.append('\t},')
    lines += ['};', '', '#endif', '']
    return '\n'.join(lines)


if __name__ == '__main__':
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('kernel_elf', type=Path)
    parser.add_argument('output', type=Path)
    args = parser.parse_args()
    args.output.write_text(extract(args.kernel_elf.read_bytes()))
